def local_chat_reply(
    question: str,
    facts: dict[str, Any] | None = None,
    *,
    has_project: bool = False,
    history: list[dict[str, str]] | None = None,
) -> str:
    """Короткий ответ по вопросу: норма, ошибка на плане, как исправить."""
    query = (question or "").strip()
    if not query:
        return "Напишите вопрос: например, сколько F207 на А23 или чем ПП23 отличается от П23."

    lowered = query.lower().replace("ё", "е")
    facts = facts or {}
    last_user = ""
    for item in reversed(history or []):
        if str(item.get("role") or "") == "user":
            last_user = str(item.get("content") or "").lower().replace("ё", "е")
            break
    material_question = lowered
    already_specific = bool(
        _detect_armature(lowered)
        or _detect_topic_10(lowered)
        or _detect_support_10(lowered)
        or re.search(r"арматур|материал|лент|изолятор|каки[ех]\s+опор|какую\s+опор|10\s*кв|10кв|0[,.]4", lowered)
    )
    if (
        last_user
        and not already_specific
        and len(lowered) < 48
        and re.search(r"\b(а|и|ну)\b|\bна\b|\bдля\b", lowered)
        and (
            _detect_armature(last_user)
            or _detect_topic_10(last_user)
            or re.search(r"арматур|материал|лент|изолятор", last_user)
        )
    ):
        material_question = f"{last_user} {lowered}"

    greeting_only = bool(
        re.fullmatch(
            r"(привет|здравствуй(те)?|добрый день|добрый вечер|как дела|как ты)[\s?!.]*",
            lowered,
        )
    )
    if greeting_only:
        if has_project:
            return (
                "На связи. Могу сказать, что не так на этом плане и как поправить. "
                "Спросите: «что не так?» или «сколько F207 на А23»."
            )
        return (
            "На связи. Могу коротко по нормам: опоры, арматура, пролёты, заземления. "
            "Спросите, например: «чем ПП23 отличается от П23»."
        )

    angle_reply = _angle_reply(lowered)
    if angle_reply:
        return sanitize_chat_reply(angle_reply)[:1800]

    layer_reply = _layer_reply(lowered)
    if layer_reply:
        return sanitize_chat_reply(layer_reply)[:1800]

    armature_reply = _armature_reply(material_question, facts, has_project=has_project)
    if armature_reply:
        return sanitize_chat_reply(armature_reply)[:1800]

    pole_reply = _pole_choice_reply(lowered)
    if pole_reply:
        return sanitize_chat_reply(pole_reply)[:1800]

    duplicate_reply = _duplicate_reply(lowered, facts, has_project=has_project)
    if duplicate_reply:
        return sanitize_chat_reply(duplicate_reply)[:1800]

    prior_user = " ".join(
        str(item.get("content") or "")
        for item in (history or [])
        if str(item.get("role") or "") == "user"
    ).lower().replace("ё", "е")
    layout_reply = _layout_estimate_reply(
        lowered,
        prior_user,
        has_project=has_project,
    )
    if layout_reply:
        return sanitize_chat_reply(layout_reply)[:1800]

    findings_reply = _findings_reply(lowered, facts, has_project=has_project)
    if findings_reply:
        return sanitize_chat_reply(findings_reply)[:1800]

    count_reply = _project_counts_reply(lowered, facts, has_project=has_project)
    if count_reply:
        return sanitize_chat_reply(count_reply)[:1800]

    support_reply = _support_reply(lowered)
    if support_reply:
        return sanitize_chat_reply(support_reply)[:1800]

    span_reply = _span_or_ground_reply(lowered, facts, has_project=has_project)
    if span_reply:
        return sanitize_chat_reply(span_reply)[:1800]

    knowledge = _knowledge_reply(lowered)
    if knowledge:
        if has_project:
            extra = _project_fallback_reply(lowered, facts)
            if extra and extra not in knowledge and "явных замечаний нет" not in extra:
                return sanitize_chat_reply(knowledge + "\n\nПо вашему проекту: " + extra)[:1800]
        return sanitize_chat_reply(knowledge)[:1800]

    if has_project:
        fallback = _project_fallback_reply(lowered, facts)
        if fallback:
            return sanitize_chat_reply(fallback)[:1800]

    return sanitize_chat_reply(_DEFAULT_GUIDE)[:1800]


