def human_field_name(key: str) -> str:
    clean = str(key or "").strip().strip("{}")
    return FIELD_NAMES.get(clean, clean)


def sanitize_chat_reply(text: str) -> str:
    reply = str(text or "").strip()
    if not reply:
        return reply
    reply = re.sub(r"```(?:latex|tex|markdown)?", "", reply)
    reply = reply.replace("```", "")
    reply = re.sub(r"\\\[(.+?)\\\]", r"\1", reply, flags=re.S)
    reply = re.sub(r"\\\((.+?)\\\)", r"\1", reply, flags=re.S)
    reply = re.sub(r"\$\$(.+?)\$\$", r"\1", reply, flags=re.S)
    reply = re.sub(r"\$(.+?)\$", r"\1", reply)
    reply = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", reply)
    reply = re.sub(r"\\text\{([^}]*)\}", r"\1", reply)
    reply = re.sub(r"\{\{([A-Za-zА-Яа-я0-9_\-]+)\}\}", lambda match: human_field_name(match.group(1)), reply)
    reply = reply.replace("placeholder", "поле").replace("Placeholder", "поле")
    cleaned_lines: list[str] = []
    for line in reply.splitlines():
        lowered = line.lower()
        if lowered.startswith(("запрещено", "ты — инженер", "ты - инженер", "говори как коллега")):
            continue
        if "имена полей в двойных" in lowered or "отвечай строго json" in lowered:
            continue
        cleaned_lines.append(line)
    reply = "\n".join(cleaned_lines)
    return re.sub(r"\n{3,}", "\n\n", reply).strip()


