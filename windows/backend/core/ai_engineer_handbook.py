def _knowledge_reply(question: str) -> str:
    ranked: list[tuple[int, str]] = []
    tokens = [token for token in re.findall(r"[а-яa-z0-9*]{3,}", question) if token not in _CHAT_STOP]
    for keywords, answer in KNOWLEDGE_CARDS:
        score = 0
        hay = (" ".join(keywords) + " " + answer).lower().replace("ё", "е")
        for key in keywords:
            if key.replace("ё", "е") in question:
                score += 3
        score += sum(1 for token in tokens if token in hay)
        if score:
            ranked.append((score, answer))
    if not ranked:
        return ""
    ranked.sort(key=lambda item: item[0], reverse=True)
    if ranked[0][0] < 2:
        return ""
    picked = [answer for score, answer in ranked[:2] if score >= 2]
    return "\n\n".join(picked)


