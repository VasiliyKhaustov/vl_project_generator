def _format_findings(items: list[dict[str, Any]], *, limit: int = 3) -> str:
    chunks: list[str] = []
    for item in items[:limit]:
        title = str(item.get("замечание") or "").strip()
        why = str(item.get("почему") or "").strip()
        how = str(item.get("как_исправить") or "").strip()
        if not title:
            continue
        piece = title.rstrip(".")
        if why:
            piece += f". Почему: {why.rstrip('.')}"
        if how:
            piece += f". Как исправить: {how.rstrip('.')}"
        chunks.append(piece + ".")
    extra = len(items) - limit
    if extra > 0:
        chunks.append(f"Ещё замечаний: {extra}.")
    return " ".join(chunks)


def _score_finding(question: str, item: dict[str, Any]) -> int:
    blob = " ".join(
        str(item.get(key) or "")
        for key in ("id", "категория", "замечание", "почему", "как_исправить")
    ).lower().replace("ё", "е")
    score = 0
    pairs = (
        ("дубл", "дубл"),
        ("номер", "номер"),
        ("пролет", "пролет"),
        ("заземл", "заземл"),
        ("угол", "угл"),
        ("полилин", "полилин"),
        ("трасс", "полилин"),
        ("тип", "тип"),
        ("слой", "слой"),
    )
    for needle, hay in pairs:
        if needle in question and hay in blob:
            score += 4
    tokens = [token for token in re.findall(r"[а-яa-z0-9*]{4,}", question) if token not in _CHAT_STOP]
    score += sum(1 for token in tokens if token in blob)
    return score


